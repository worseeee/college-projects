%% 任务2：运输系统货运量预测 BP神经网络
% FREIGHT_FORECAST_BP 基于BP神经网络的运输系统货运量预测
%   本脚本基于8项经济指标预测第9年的货运总量、铁路及公路货运量。
%   包含数据归一化、BP网络训练、反归一化及误差分析。
clear; clc; close all;

%% 1. 导入原始数据 
% 这是一个 8行 x 9列 的输入矩阵（8项指标，9年数据）
% 请按你实验报告中的数据修改 P 矩阵！每一列代表一年的8个输入指标
P = [
    % 例: 第1年 第2年 第3年 ... 第9年
    58478, 67884, 74462, 78345, 82067, 89430, 95933, 104790, 116694; % 指标1: GDP
    135185, 152369, 182563, 201587, 225689, 240568, 263856, 285697, 308765; % 指标2: 工业总产值
    5.64, 5.64, 6.01, 6.12, 6.21, 6.37, 6.38, 6.65, 6.65;
    0.23, 0.27, 0.25, 0.26, 0.26, 0.28, 0.28, 0.30, 0.30;
    16.5, 18.7, 21.6, 25.8, 30.5, 34.9, 39.8, 42.5, 46.7;
    0.21, 0.26, 0.28, 0.29, 0.31, 0.33, 0.36, 0.39, 0.41;
    1005.3, 1105.6, 1204.6, 1316.5, 1423.5, 1536.2, 1632.6, 1753.2, 1865.5;
    585.44, 575.03, 601.23, 627.89, 676.95, 716.32, 765.24, 812.22, 875.26;
];

% 这是一个 3行 x 9列 的目标矩阵（3项输出指标：货运总量、铁路、公路）
T = [
    % 例: 第1年 第2年 第3年 ... 第9年
    102569, 124587, 148792, 162568, 186592, 205862, 226598, 245636, 263595; % 输出1: 货运总量
    52365, 60821, 69253, 79856, 91658, 99635, 109862, 120566, 130378;  % 输出2: 铁路货运量
    46251, 56245, 67362, 78165, 90548, 98758, 102564, 111257, 120356;  % 输出3: 公路货运量
];

%% 2. 划分训练集与测试集
% 依据报告要求：前8个样本作为训练集，最后1个（第9年）作为测试集
P_train = P(:, 1:8); % 训练输入 (8x8)
T_train = T(:, 1:8); % 训练目标 (3x8)

P_test  = P(:, 9);   % 测试输入 (8x1)
T_test  = T(:, 9);   % 测试目标真值 (3x1)

%% 3. 数据归一化 
% 将输入数据归一化到 [-1, 1] 之间 (适应隐含层 tansig)
% ps_input 是记录缩放比例的“钥匙”，后续测试集必须用同一把钥匙
[P_train_norm, ps_input] = mapminmax(P_train, -1, 1);

% 将输出目标归一化到 [0, 1] 之间 (严格适应输出层 logsig)
[T_train_norm, ps_output] = mapminmax(T_train, 0, 1);

%% 4. 创建与配置 BP 神经网络
% 输入层8个，输出层3个, 隐含层17个
hiddenLayerSize = 17; 
net = feedforwardnet(hiddenLayerSize, 'trainlm'); % 使用 trainlm 算法

% 配置激活函数
net.layers{1}.transferFcn = 'tansig'; % 隐含层 S型正切
net.layers{2}.transferFcn = 'logsig'; % 输出层 S型对数 (输出范围0~1)

% 训练参数设置
net.trainParam.epochs = 1000;
net.trainParam.goal = 1e-5; % 预测问题通常要求更小的误差
net.trainParam.showWindow = true; % 显示训练窗口

%% 5. 训练网络
[net, tr] = train(net, P_train_norm, T_train_norm);

%% 6. 仿真与测试 
% 步骤 A: 对测试集的输入数据，使用刚才训练集的“钥匙”进行归一化
P_test_norm = mapminmax('apply', P_test, ps_input);

% 步骤 B: 将归一化后的测试数据送入网络进行仿真预测
T_sim_norm = sim(net, P_test_norm);

% 步骤 C: 将网络输出的 [0,1] 之间的数值，反归一化解压回真实的货运量！
T_sim = mapminmax('reverse', T_sim_norm, ps_output);

%% 7. 结果展示与误差计算
disp('------------------------------------------------');
disp('第9年货运量真实值 (T_test):');
disp(T_test);
disp('网络预测的第9年货运量 (T_sim):');
disp(T_sim);

% 计算相对误差百分比: |预测值 - 真实值| / 真实值 * 100%
relative_error = abs(T_sim - T_test) ./ T_test * 100;
disp('预测相对误差 (%):');
disp(relative_error);

% 绘制真实的与预测的货运量对比柱状图
figure;
bar([T_test, T_sim]);
legend('真实值', '预测值');
set(gca, 'XTickLabel', {'货运总量', '铁路货运量', '公路货运量'});
title('第9年货运量预测对比');
ylabel('货运量 (万吨)');
grid on;